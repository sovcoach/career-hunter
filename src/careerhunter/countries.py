_PUNCT = re.compile(r"[^\w&]+")


def _fold(text: str) -> str:
    plain = unicodedata.normalize("NFKD", text)
    plain = "".join(ch for ch in plain if not unicodedata.combining(ch))
    plain = plain.replace("&", " and ").replace(".", "")
    return " ".join(_PUNCT.sub(" ", plain).casefold().split())


_FOLDED = frozenset(_fold(name) for name in _NAMES)


def is_country(text: str) -> bool:
    """True when `text` is only a country's name, such as "Canada" or "U.S.A."."""
    folded = _fold(text)
    if folded.startswith("the "):
        folded = folded[4:]
    return bool(folded) and folded in _FOLDED
